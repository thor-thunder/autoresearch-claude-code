import re
import subprocess
import sys
import time

# ── Configuration ──────────────────────────────────────────────────────────────

TRAIN_CMD = ["python3", "train.py"]

PRIMARY_METRIC = "val_accuracy"
PRIMARY_DIRECTION = "higher"

# Regex fallbacks — used only if train.py doesn't emit native METRIC lines.
FALLBACK_PATTERNS = [
    (re.compile(r"(?:val[_\s]?accuracy|validation[_\s]?acc)[=:\s]+([0-9.]+)", re.IGNORECASE), "val_accuracy"),
    (re.compile(r"(?:val[_\s]?f1|f1[_\s]?score)[=:\s]+([0-9.]+)", re.IGNORECASE), "val_f1"),
    (re.compile(r"(?:val[_\s]?loss|validation[_\s]?loss)[=:\s]+([0-9.]+)", re.IGNORECASE), "val_loss"),
    (re.compile(r"\baccuracy[:\s]+([0-9.]+)", re.IGNORECASE), "val_accuracy"),
]

# ── Implementation ─────────────────────────────────────────────────────────────


def run_training() -> tuple[str, str, int, float]:
    start = time.perf_counter()
    result = subprocess.run(TRAIN_CMD, capture_output=True, text=True)
    elapsed = time.perf_counter() - start
    return result.stdout, result.stderr, result.returncode, elapsed


def extract_metrics(stdout: str, stderr: str) -> dict[str, float]:
    combined = stdout + "\n" + stderr
    metrics: dict[str, float] = {}

    # Native METRIC lines take priority
    for line in combined.splitlines():
        m = re.match(r"METRIC\s+(\w+)=([0-9.]+)", line.strip())
        if m:
            metrics[m.group(1)] = float(m.group(2))

    if metrics:
        return metrics

    # Fallback: common log patterns
    for pattern, canonical_name in FALLBACK_PATTERNS:
        for m in pattern.finditer(combined):
            if canonical_name not in metrics:
                metrics[canonical_name] = float(m.group(1))

    return metrics


def main() -> None:
    print(f"Running: {' '.join(TRAIN_CMD)}", flush=True)
    stdout, stderr, exit_code, elapsed = run_training()

    if exit_code != 0:
        print("Training script failed:", file=sys.stderr)
        print(stdout[-2000:], file=sys.stderr)
        print(stderr[-1000:], file=sys.stderr)
        sys.exit(1)

    metrics = extract_metrics(stdout, stderr)

    if not metrics:
        print("ERROR: no metrics found in training output.", file=sys.stderr)
        print("Make train.py emit lines like:", file=sys.stderr)
        print("  METRIC val_accuracy=0.923", file=sys.stderr)
        print("  METRIC val_f1=0.918", file=sys.stderr)
        print(f"\nActual stdout:\n{stdout[-2000:]}", file=sys.stderr)
        sys.exit(1)

    if PRIMARY_METRIC not in metrics:
        first_key = next(iter(metrics))
        metrics[PRIMARY_METRIC] = metrics[first_key]
        print(
            f"WARNING: '{PRIMARY_METRIC}' not found; aliasing from '{first_key}'",
            file=sys.stderr,
        )

    for name, value in metrics.items():
        print(f"METRIC {name}={value:.6f}")

    direction_word = "higher" if PRIMARY_DIRECTION == "higher" else "lower"
    best = metrics.get(PRIMARY_METRIC, "N/A")
    print(f"\nDone in {elapsed:.1f}s | {PRIMARY_METRIC}={best} ({direction_word} is better)", file=sys.stderr)


if __name__ == "__main__":
    main()
