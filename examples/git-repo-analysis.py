#!/usr/bin/env python3
"""
autoresearch_bench.py — generated by git-repo skill for a Python ML repo.

Detected stack:
  Language:    Python 3
  Framework:   scikit-learn / XGBoost
  Test runner: pytest
  Metric:      val_accuracy (higher is better), secondary: val_f1

Edit train.py (or the model config) to run experiments.
This script measures the result and outputs METRIC lines for autoresearch.

Usage:
  python3 autoresearch_bench.py
"""

import subprocess
import sys
import re
import time

# ── Configuration ─────────────────────────────────────────────────────────────

TRAIN_CMD = ["python3", "train.py"]

# Patterns to extract metrics from training output.
# The script first looks for native METRIC lines, then falls back to these.
METRIC_PATTERNS = [
    re.compile(r"(?:val[_\s]?accuracy|validation[_\s]?acc)[=:\s]+([0-9.]+)", re.IGNORECASE),
    re.compile(r"(?:val[_\s]?f1|f1[_\s]?score)[=:\s]+([0-9.]+)", re.IGNORECASE),
    re.compile(r"(?:val[_\s]?loss|validation[_\s]?loss)[=:\s]+([0-9.]+)", re.IGNORECASE),
    re.compile(r"\baccuracy[:\s]+([0-9.]+)", re.IGNORECASE),
]

PATTERN_TO_METRIC = {
    "accuracy": "val_accuracy",
    "val_accuracy": "val_accuracy",
    "validation_acc": "val_accuracy",
    "f1": "val_f1",
    "val_f1": "val_f1",
    "val_loss": "val_loss",
    "validation_loss": "val_loss",
}

PRIMARY_METRIC = "val_accuracy"
PRIMARY_DIRECTION = "higher"

# ── Implementation ─────────────────────────────────────────────────────────────

def run_training() -> tuple[str, str, int, float]:
    start = time.perf_counter()
    result = subprocess.run(TRAIN_CMD, capture_output=True, text=True)
    elapsed = time.perf_counter() - start
    return result.stdout, result.stderr, result.returncode, elapsed


def extract_metrics(stdout: str, stderr: str) -> dict[str, float]:
    combined = stdout + "\n" + stderr
    metrics: dict[str, float] = {}

    # First pass: native METRIC lines (autoresearch format)
    for line in combined.splitlines():
        stripped = line.strip()
        if stripped.startswith("METRIC "):
            parts = stripped[7:].split("=", 1)
            if len(parts) == 2:
                try:
                    metrics[parts[0].strip()] = float(parts[1].strip())
                except ValueError:
                    pass

    if metrics:
        return metrics

    # Second pass: common log patterns
    for pattern in METRIC_PATTERNS:
        for m in pattern.finditer(combined):
            matched_text = m.group(0).lower()
            value = float(m.group(1))
            for keyword, canonical in PATTERN_TO_METRIC.items():
                if keyword.replace("_", " ") in matched_text.replace("_", " "):
                    if canonical not in metrics:
                        metrics[canonical] = value
                    break

    return metrics


def main() -> None:
    print(f"Running: {' '.join(TRAIN_CMD)}", flush=True)

    stdout, stderr, exit_code, elapsed = run_training()

    if exit_code != 0:
        print("Training failed:", file=sys.stderr)
        print(stdout[-2000:], file=sys.stderr)
        print(stderr[-1000:], file=sys.stderr)
        sys.exit(1)

    metrics = extract_metrics(stdout, stderr)

    if not metrics:
        print("ERROR: no metrics found in training output.", file=sys.stderr)
        print("Ensure train.py prints lines like:", file=sys.stderr)
        print("  METRIC val_accuracy=0.923", file=sys.stderr)
        print("  METRIC val_f1=0.918", file=sys.stderr)
        print("\nActual output was:", file=sys.stderr)
        print(stdout[-2000:], file=sys.stderr)
        sys.exit(1)

    if PRIMARY_METRIC not in metrics:
        first_key = next(iter(metrics))
        metrics[PRIMARY_METRIC] = metrics[first_key]
        print(
            f"WARNING: '{PRIMARY_METRIC}' not found; using '{first_key}'={metrics[first_key]:.6f}",
            file=sys.stderr,
        )

    for name, value in metrics.items():
        print(f"METRIC {name}={value:.6f}")

    direction_word = "higher" if PRIMARY_DIRECTION == "higher" else "lower"
    print(f"\nCompleted in {elapsed:.1f}s | {PRIMARY_METRIC}={metrics.get(PRIMARY_METRIC, 'N/A')} ({direction_word} is better)")


if __name__ == "__main__":
    main()
